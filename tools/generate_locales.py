def escape_android(value: str) -> str:
    escaped = xml.sax.saxutils.escape(value, {"'": r"\'", '"': r"\""})
    return escaped


def write_android_xml(folder: str, strings: dict[str, str]) -> None:
    directory = ANDROID_RES / folder
    directory.mkdir(parents=True, exist_ok=True)
    lines = ['<?xml version="1.0" encoding="utf-8"?>', "<resources>"]
    for key, value in strings.items():
        lines.append(f'    <string name="{key}">{escape_android(value)}</string>')
    lines.append("</resources>")
    lines.append("")
    (directory / "strings.xml").write_text("\n".join(lines), encoding="utf-8")


def merged(locale: str) -> dict[str, str]:
    data = dict(ENGLISH)
    data.update(BRAND)
    data.update(LOCALES.get(locale, {}))
    data.update(BRAND)
    return data


def write_ios_catalog() -> None:
    strings: dict[str, dict] = {}
    ios_locales = {
        "en": ENGLISH,
        **{k.replace("-r", "-"): merged(k) for k in LOCALES},
    }
    # Normalize Android folders to BCP-47 for Xcode
    remap = {
        "pt-BR": "pt-BR",
        "zh-CN": "zh-Hans",
        "zh-TW": "zh-Hant",
        "iw": "he",
    }
    normalized: dict[str, dict[str, str]] = {"en": dict(ENGLISH)}
    for folder, payload in LOCALES.items():
        bcp = folder.replace("-r", "-")
        bcp = remap.get(bcp, bcp)
        normalized[bcp] = merged(folder)

    for key in ENGLISH:
        localizations = {}
        for locale, payload in normalized.items():
            localizations[locale] = {
                "stringUnit": {
                    "state": "translated",
                    "value": payload.get(key, ENGLISH[key]),
                }
            }
        strings[key] = {
            "extractionState": "manual",
            "localizations": localizations,
        }

    catalog = {
        "sourceLanguage": "en",
        "strings": strings,
        "version": "1.0",
    }
    IOS_STRINGS.parent.mkdir(parents=True, exist_ok=True)
    IOS_STRINGS.write_text(json.dumps(catalog, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")


def main() -> None:
    write_android_xml("values", {**ENGLISH, **BRAND})
    for folder in LOCALES:
        write_android_xml(f"values-{folder}", merged(folder))
    write_ios_catalog()
    print(f"Wrote {1 + len(LOCALES)} Android locale folders and {IOS_STRINGS}")


